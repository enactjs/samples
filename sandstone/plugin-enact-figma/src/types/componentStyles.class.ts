/**
 * Represents the styles of a custom component extracted from a Figma design.
 * This class encapsulates various style properties such as dimensions, colors, and positioning.
 */
class CustomComponentStyles {
	/**
	 * The background color of the component, represented as a CSS color string.
	 */
	backgroundColor?: string;
	/**
	 * The border radius of the component, represented as a string.
	 */
	borderRadius?: string;
	/**
	 * The text color of the component, represented as a CSS color string.
	 */
	color?: string;
	/**
	 * The font size of the component's text, represented as a string.
	 */
	fontSize?: string;
	/**
	 * The height of the component, represented as a string.
	 */
	height?: string;
	/**
	 * The left position of the component, represented as a string.
	 */
	left?: string;
	/**
	 * The opacity of the component, represented as a string.
	 */
	opacity?: string;
	/**
	 * The padding of the component, represented as a CSS-like string.
	 */
	padding?: string;
	/**
	 * The top position of the component, represented as a string.
	 */
	top?: string;
	/**
	 * The width of the component, represented as a string.
	 */
	width?: string;
}

export default CustomComponentStyles;
